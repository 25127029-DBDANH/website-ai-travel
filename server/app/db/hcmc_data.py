# Full dataset
# ---------------------------------------------------------------------------
PLACES: list[dict] = _Q1 + _Q3 + _Q4 + _Q5 + _BT + _PN + _TD + _Q7


# ---------------------------------------------------------------------------
# Seed function (ORM-based)
# ---------------------------------------------------------------------------
async def seed_places(session: Any = None) -> None:
    """
    Insert or update (upsert) all places using SQLAlchemy ORM.
    - Inserts new places if name not in DB.
    - Updates attributes if place already exists by name.
    Compatible with both SQLite (aiosqlite) and PostgreSQL (asyncpg).
    """
    from sqlalchemy import select

    from app.db.models import Place
    from app.db.session import AsyncSessionLocal

    async def _do_seed(s: Any) -> None:
        result = await s.execute(select(Place))
        existing_places: dict[str, Place] = {}
        extra_duplicates: list[Place] = []
        for place in result.scalars():
            if place.name in existing_places:
                extra_duplicates.append(place)
            else:
                existing_places[place.name] = place

        dataset_names = {p["name"] for p in PLACES}
        inserted = updated = deactivated = 0
        updatable_fields = (
            "name_vi",
            "address",
            "district",
            "latitude",
            "longitude",
            "category",
            "is_indoor",
            "open_time",
            "close_time",
            "entry_fee_vnd",
            "average_rating",
            "photo_url",
            "photo_is_generic",
            "description",
            "tags",
            "is_active",
        )

        for p in PLACES:
            existing = existing_places.get(p["name"])
            if existing:
                changed = False
                for field in updatable_fields:
                    new_val = p.get(field)
                    if getattr(existing, field) != new_val:
                        setattr(existing, field, new_val)
                        changed = True
                if changed:
                    updated += 1
            else:
                s.add(Place(**p))
                inserted += 1

        for existing_name, existing in existing_places.items():
            if existing_name not in dataset_names and existing.is_active:
                existing.is_active = False
                deactivated += 1

        for duplicate in extra_duplicates:
            if duplicate.is_active:
                duplicate.is_active = False
                deactivated += 1

        if inserted or updated or deactivated:
            await s.commit()
        print(
            f"✅ Seed hoàn thành — thêm: {inserted}, cập nhật: {updated}, ẩn (cũ): {deactivated}"
        )
        print(f"   Tổng địa điểm trong dataset: {len(PLACES)}")

    if session is not None:
        await _do_seed(session)
    else:
        async with AsyncSessionLocal() as sess:
            await _do_seed(sess)


if __name__ == "__main__":
    import logging
    logging.basicConfig(level=logging.INFO)
    asyncio.run(seed_places())
