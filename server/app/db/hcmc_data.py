async def seed_places() -> None:
    """Insert all places into the database (skip if already exists by name+address)."""
    async with AsyncSessionLocal() as session:
        inserted = 0
        skipped = 0
        for p in PLACES:
            # Check duplicate by name
            result = await session.execute(
                text("SELECT id FROM places WHERE name = :name LIMIT 1"),
                {"name": p["name"]},
            )
            if result.fetchone():
                skipped += 1
                continue

            await session.execute(
                text(
                    """
                    INSERT INTO places (
                        id, name, name_vi, address, district,
                        latitude, longitude, category, is_indoor,
                        open_time, close_time, entry_fee_vnd,
                        average_rating, description, tags
                    ) VALUES (
                        :id, :name, :name_vi, :address, :district,
                        :latitude, :longitude, :category, :is_indoor,
                        :open_time, :close_time, :entry_fee_vnd,
                        :average_rating, :description, :tags
                    )
                    """
                ),
                {
                    "id": str(uuid4()),
                    "name": p["name"],
                    "name_vi": p.get("name_vi"),
                    "address": p["address"],
                    "district": p["district"],
                    "latitude": p["latitude"],
                    "longitude": p["longitude"],
                    "category": p["category"],
                    "is_indoor": p.get("is_indoor", False),
                    "open_time": p.get("open_time"),
                    "close_time": p.get("close_time"),
                    "entry_fee_vnd": p.get("entry_fee_vnd", 0),
                    "average_rating": p.get("average_rating"),
                    "description": p.get("description"),
                    "tags": p.get("tags", []),
                },
            )
            inserted += 1

        await session.commit()
        logger.info("Seed complete — inserted: %d, skipped (dup): %d", inserted, skipped)
        print(f"✅ Seed complete — inserted: {inserted}, skipped (dup): {skipped}")


if __name__ == "__main__":
    logging.basicConfig(level=logging.INFO)
    asyncio.run(seed_places())
